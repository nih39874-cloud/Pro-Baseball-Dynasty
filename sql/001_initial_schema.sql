create table if not exists public.leagues (
 id uuid primary key default gen_random_uuid(),
 kind text not null unique check (kind in ('gm','official')),
 current_year integer not null default 2024,
 season_start_tz text not null default 'Asia/Taipei',
 time_control boolean not null default false,
 created_at timestamptz not null default now()
);
insert into public.leagues(kind,time_control) values('gm',true),('official',false) on conflict(kind) do nothing;

create table if not exists public.memberships (
 user_id uuid not null references auth.users(id) on delete cascade,
 league_id uuid not null references public.leagues(id) on delete cascade,
 team_id text references public.teams(id),
 role text not null check (role in ('gm','manager')),
 primary key(user_id,league_id),
 check ((role='gm' and team_id is null) or (role='manager' and team_id is not null))
);
create unique index if not exists league_team_unique on public.memberships(league_id,team_id) where team_id is not null;

create table if not exists public.players_master (
 id bigint generated by default as identity primary key,
 cpbl_id text unique, full_name text not null,
 birth_date date, bats text, throws text, primary_position text,
 initial_team_id text references public.teams(id),
 source_year integer not null default 2024,
 source_type text not null default 'import_pending',
 source_license text,
 created_at timestamptz not null default now()
);
create table if not exists public.league_players (
 id uuid primary key default gen_random_uuid(),
 league_id uuid not null references public.leagues(id),
 master_player_id bigint not null references public.players_master(id),
 team_id text references public.teams(id),
 roster_status text not null default 'reserve' check(roster_status in ('active','reserve','free_agent','retired')),
 monthly_salary_ntd bigint not null default 0 check(monthly_salary_ntd>=0),
 contract_years integer not null default 1,
 fa_service_seasons numeric(6,3) not null default 0,
 batting_rating numeric(6,2), pitching_rating numeric(6,2), fielding_rating numeric(6,2),
 updated_at timestamptz not null default now(),
 unique(league_id,master_player_id)
);
create table if not exists public.team_finances (
 league_id uuid not null references public.leagues(id),
 team_id text not null references public.teams(id),
 cash_ntd bigint not null default 500000000 check(cash_ntd>=0),
 updated_at timestamptz not null default now(),
 primary key(league_id,team_id)
);
insert into public.team_finances(league_id,team_id)
 select l.id,t.id from public.leagues l cross join public.teams t
on conflict do nothing;

create table if not exists public.games (
 id uuid primary key default gen_random_uuid(),
 league_id uuid not null references public.leagues(id),
 season_year integer not null,
 home_team_id text not null references public.teams(id),
 away_team_id text not null references public.teams(id),
 scheduled_at timestamptz not null,
 phase text not null default 'scheduled',
 home_score integer not null default 0, away_score integer not null default 0,
 game_state jsonb not null default '{}'::jsonb,
 version bigint not null default 0,
 updated_at timestamptz not null default now(),
 check(home_team_id<>away_team_id)
);
create index if not exists games_league_schedule on public.games(league_id,scheduled_at);
create table if not exists public.game_events (
 id bigint generated always as identity primary key,
 game_id uuid not null references public.games(id) on delete cascade,
 seq bigint not null,
 type text not null,
 payload jsonb not null,
 created_at timestamptz not null default now(),
 unique(game_id,seq)
);
create table if not exists public.season_snapshots (
 id uuid primary key default gen_random_uuid(),
 league_id uuid not null references public.leagues(id),
 timeline_id uuid not null,
 season_year integer not null,
 snapshot jsonb not null,
 created_at timestamptz not null default now()
);
create index if not exists snapshot_timeline_year on public.season_snapshots(league_id,timeline_id,season_year);

