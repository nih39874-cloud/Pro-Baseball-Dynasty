create policy league_read on public.leagues for select to authenticated using(id in (select league_id from public.memberships where user_id=(select auth.uid())));
create policy player_master_read on public.players_master for select to authenticated using(true);
create policy league_players_read on public.league_players for select to authenticated using(league_id in (select league_id from public.memberships where user_id=(select auth.uid())));
create policy team_finances_read on public.team_finances for select to authenticated using(league_id in (select league_id from public.memberships where user_id=(select auth.uid())));
create policy games_read on public.games for select to authenticated using(league_id in (select league_id from public.memberships where user_id=(select auth.uid())));
create policy events_read on public.game_events for select to authenticated using(game_id in (select g.id from public.games g join public.memberships m on m.league_id=g.league_id where m.user_id=(select auth.uid())));
create policy snapshots_read on public.season_snapshots for select to authenticated using(league_id in (select league_id from public.memberships where user_id=(select auth.uid())));

